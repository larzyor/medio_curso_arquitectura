// Generador de clases C# a partir del XSD oficial de UBL 2.1 (equivalente a xsd.exe / XmlSchemaClassGenerator).
// Uso:  dotnet run --project tools/ABC.Billing.GenerarClasesUbl -- <UBL-Invoice-2.1.xsd> <archivo-salida.cs>
// Parte del elemento global "Invoice", recorre todos los tipos alcanzables y emite una clase por tipo, con los
// atributos de XmlSerializer (nombre, espacio de nombres y ORDEN) tomados del propio esquema.
using System.Text;
using System.Xml;
using System.Xml.Schema;

if (args.Length != 2) { Console.Error.WriteLine("Uso: GenerarClasesUbl <UBL-Invoice-2.1.xsd> <salida.cs>"); return 2; }

var rutaXsd = Path.GetFullPath(args[0]);
var set = new XmlSchemaSet { XmlResolver = new XmlUrlResolver() };
var cargados = new Dictionary<string, XmlSchema>(StringComparer.OrdinalIgnoreCase);
XmlSchema Cargar(string ruta)
{
    if (cargados.TryGetValue(ruta, out var s)) return s;
    using var r = XmlReader.Create(ruta, new XmlReaderSettings { DtdProcessing = DtdProcessing.Parse, XmlResolver = new XmlUrlResolver() });
    var schema = XmlSchema.Read(r, null)!;
    cargados[ruta] = schema;
    foreach (var ext in schema.Includes.OfType<XmlSchemaExternal>().Where(e => !string.IsNullOrEmpty(e.SchemaLocation)))
        ext.Schema = Cargar(Path.GetFullPath(Path.Combine(Path.GetDirectoryName(ruta)!, ext.SchemaLocation)));
    return schema;
}
set.Add(Cargar(rutaXsd));
set.Compile();

var raiz = set.GlobalElements.Values.OfType<XmlSchemaElement>().Single(e => e.Name == "Invoice");
var nombres = new Dictionary<XmlQualifiedName, string>();   // tipo complejo -> nombre de clase
var cola = new Queue<XmlSchemaComplexType>();
var usados = new HashSet<string>();

string NombreClase(XmlSchemaComplexType t)
{
    if (nombres.TryGetValue(t.QualifiedName, out var n)) return n;
    n = t.Name!;
    if (!usados.Add(n)) { n = Prefijo(t.QualifiedName.Namespace) + n; usados.Add(n); }
    nombres[t.QualifiedName] = n; cola.Enqueue(t); return n;
}
static string Prefijo(string ns) => ns.Contains("CommonAggregate") ? "Cac" : ns.Contains("CommonBasic") ? "Cbc" : ns.Contains("Extension") ? "Ext" : "Tipo";

// Tipo C# de un tipo simple (por su tipo base primitivo de XSD)
static string TipoPrimitivo(XmlSchemaType? t)
{
    var codigo = (t?.Datatype ?? (t as XmlSchemaComplexType)?.Datatype)?.TypeCode ?? XmlTypeCode.String;
    return codigo switch
    {
        XmlTypeCode.Decimal or XmlTypeCode.Float or XmlTypeCode.Double => "decimal",
        XmlTypeCode.Integer or XmlTypeCode.Int or XmlTypeCode.Long or XmlTypeCode.NonNegativeInteger or XmlTypeCode.PositiveInteger
            or XmlTypeCode.UnsignedInt or XmlTypeCode.Short => "long",
        XmlTypeCode.Boolean => "bool",
        _ => "string"   // cadenas, códigos, URI y también fecha/hora (se escriben tal cual: yyyy-MM-dd, hh:mm:ss)
    };
}

var sb = new StringBuilder();
sb.AppendLine("// <auto-generated>");
sb.AppendLine("// Generado por tools/ABC.Billing.GenerarClasesUbl a partir de UBL-Invoice-2.1.xsd (OASIS UBL 2.1).");
sb.AppendLine("// NO EDITAR A MANO: para regenerar, ver el README de la carpeta tools.");
sb.AppendLine("// </auto-generated>");
sb.AppendLine("#nullable enable");
sb.AppendLine("#pragma warning disable CS8618, CS1591, CS0108");
sb.AppendLine("using System.Xml;");
sb.AppendLine("using System.Xml.Serialization;");
sb.AppendLine();
sb.AppendLine("namespace ABC.Billing.Infrastructure.UblEngine.Generado;");
sb.AppendLine();

var tipoRaiz = (XmlSchemaComplexType)raiz.ElementSchemaType!;
var nombreRaiz = NombreClase(tipoRaiz);
var sbClases = new StringBuilder();

int total = 0;
while (cola.Count > 0)
{
    var t = cola.Dequeue();
    var nombre = nombres[t.QualifiedName];
    total++;
    var cuerpo = new StringBuilder();
    var propiedades = new HashSet<string> { nombre };
    int orden = 0;

    string NombrePropiedad(string baseNombre)
    {
        var p = char.ToUpperInvariant(baseNombre[0]) + baseNombre[1..];
        while (!propiedades.Add(p)) p += "1";
        return p;
    }

    void Particula(XmlSchemaParticle? part, bool opcionalPadre)
    {
        switch (part)
        {
            case XmlSchemaSequence sec:
                foreach (var h in sec.Items.OfType<XmlSchemaParticle>()) Particula(h, opcionalPadre || sec.MinOccurs == 0);
                break;
            case XmlSchemaChoice ch:
                foreach (var h in ch.Items.OfType<XmlSchemaParticle>()) Particula(h, true);
                break;
            case XmlSchemaAll all:
                foreach (var h in all.Items.OfType<XmlSchemaParticle>()) Particula(h, opcionalPadre);
                break;
            case XmlSchemaAny:
                cuerpo.AppendLine("    [XmlAnyElement]");
                cuerpo.AppendLine("    public XmlElement? Any { get; set; }");
                cuerpo.AppendLine();
                break;
            case XmlSchemaElement e:
            {
                var decl = e.RefName.IsEmpty ? e : (XmlSchemaElement)set.GlobalElements[e.RefName]!;
                var esc = decl.ElementSchemaType;
                bool lista = e.MaxOccurs > 1;
                bool opcional = opcionalPadre || e.MinOccurs == 0;
                string tipo = esc is XmlSchemaComplexType ct ? NombreClase(ct) : TipoPrimitivo(esc);
                string ns = decl.QualifiedName.Namespace;
                orden++;
                var prop = NombrePropiedad(decl.Name!);
                cuerpo.AppendLine($"    [XmlElement(\"{decl.Name}\", Namespace = \"{ns}\", Order = {orden})]");
                if (lista) cuerpo.AppendLine($"    public List<{tipo}> {prop} {{ get; set; }} = new();");
                else if (opcional) cuerpo.AppendLine($"    public {tipo}? {prop} {{ get; set; }}");
                else if (tipo is "decimal" or "long" or "bool") cuerpo.AppendLine($"    public {tipo} {prop} {{ get; set; }}");
                else cuerpo.AppendLine($"    public {tipo} {prop} {{ get; set; }} = default!;");
                cuerpo.AppendLine();
                break;
            }
        }
    }

    void Atributos(IEnumerable<XmlSchemaObject> items)
    {
        foreach (var a in items.OfType<XmlSchemaAttribute>())
        {
            var prop = NombrePropiedad(a.Name!);
            cuerpo.AppendLine($"    [XmlAttribute(\"{a.Name}\")]");
            cuerpo.AppendLine($"    public string? {prop} {{ get; set; }}");
            cuerpo.AppendLine();
        }
    }

    if (t.ContentModel is XmlSchemaSimpleContent sc)
    {
        // Tipos de datos de UBL (importe, código, texto...): valor + atributos (heredados por extensión)
        string tipoValor = TipoPrimitivo(t);
        cuerpo.AppendLine("    [XmlText]");
        cuerpo.AppendLine($"    public {tipoValor} Value {{ get; set; }}{(tipoValor == "string" ? " = \"\";" : "")}");
        cuerpo.AppendLine();
        propiedades.Add("Value");
        // atributos del tipo y de sus bases (aplanados)
        foreach (var a in t.AttributeUses.Values.OfType<XmlSchemaAttribute>())
        {
            var prop = NombrePropiedad(a.Name!);
            cuerpo.AppendLine($"    [XmlAttribute(\"{a.Name}\")]");
            cuerpo.AppendLine($"    public string? {prop} {{ get; set; }}");
            cuerpo.AppendLine();
        }
    }
    else
    {
        Particula(t.ContentTypeParticle, false);
        foreach (var a in t.AttributeUses.Values.OfType<XmlSchemaAttribute>())
        {
            var prop = NombrePropiedad(a.Name!);
            cuerpo.AppendLine($"    [XmlAttribute(\"{a.Name}\")]");
            cuerpo.AppendLine($"    public string? {prop} {{ get; set; }}");
            cuerpo.AppendLine();
        }
    }

    sbClases.AppendLine($"[XmlType(TypeName = \"{t.Name}\", Namespace = \"{t.QualifiedName.Namespace}\")]");
    if (t == tipoRaiz)
        sbClases.AppendLine($"[XmlRoot(\"Invoice\", Namespace = \"{raiz.QualifiedName.Namespace}\", IsNullable = false)]");
    sbClases.AppendLine($"public partial class {nombre}");
    sbClases.AppendLine("{");
    sbClases.Append(cuerpo);
    sbClases.AppendLine("}");
    sbClases.AppendLine();
}
sb.Append(sbClases);
File.WriteAllText(args[1], sb.ToString(), new UTF8Encoding(false));
Console.WriteLine($"Clases generadas: {total}. Raíz: {nombreRaiz}. Archivo: {args[1]}");
return 0;
